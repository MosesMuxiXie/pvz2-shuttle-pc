"""Tests for tools/contentc/zclasses.py (ZombieClass -> engine family table).

Run:
    python -m unittest tools.tests.test_zclasses -v
"""

from __future__ import annotations

import contextlib
import io
import json
import os
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from tools.contentc import zclasses  # noqa: E402

OBB = Path(
    os.environ.get("PVZ2_OBB_DIR") or (REPO.parent.parent / "work" / "obb_packages")
)
GENERATED_JSON = REPO / "native" / "generated" / "zombie_classes.json"
GENERATED_INC = REPO / "native" / "generated" / "zombie_family_table.inc"
HEADER = "// generated by tools/contentc/zclasses.py -- do not edit"


def load_generated() -> dict:
    return json.loads(GENERATED_JSON.read_text(encoding="utf-8"))


def records_by_name(payload: dict) -> dict[str, dict]:
    return {record["className"]: record for record in payload["classes"]}


def inc_entries() -> list[tuple[str, str]]:
    entries: list[tuple[str, str]] = []
    for line in GENERATED_INC.read_text(encoding="utf-8").splitlines():
        text = line.strip()
        if not text or text.startswith("//"):
            continue
        assert text.startswith("{") and text.endswith("},"), text
        class_name, family = text[1:-2].split(", ")
        entries.append((class_name.strip('"'), family.strip('"')))
    return entries


class FamilyTableTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.payload = load_generated()
        cls.records = records_by_name(cls.payload)

    def test_one_record_per_zombie_class(self) -> None:
        classes = [record["className"] for record in self.payload["classes"]]
        self.assertEqual(len(classes), 183)
        self.assertEqual(len(set(classes)), 183)
        self.assertEqual(sum(record["count"] for record in self.payload["classes"]), 1127)

    def test_families_are_known(self) -> None:
        for record in self.payload["classes"]:
            self.assertIn(record["family"], zclasses.FAMILIES, record["className"])
        self.assertEqual(set(self.payload["countsByFamily"]), set(zclasses.FAMILIES))

    def test_every_record_has_evidence(self) -> None:
        for record in self.payload["classes"]:
            self.assertTrue(record["evidence"], record["className"])
            self.assertTrue(all(isinstance(item, str) and item for item in record["evidence"]))
            self.assertLessEqual(len(record["sampleTypes"]), 3)
            self.assertGreaterEqual(record["count"], 1)

    def test_counts_by_family_match_records(self) -> None:
        tally = {family: 0 for family in zclasses.FAMILIES}
        for record in self.payload["classes"]:
            tally[record["family"]] += 1
        self.assertEqual(self.payload["countsByFamily"], tally)

    def test_basic_walkers_stay_walkers(self) -> None:
        basic = self.records["ZombieBasic"]
        self.assertEqual(basic["family"], "walk")
        self.assertGreaterEqual(basic["count"], 200)
        for name, record in self.records.items():
            if name.startswith("ZombieZombotany") or name in {"ZombieBeachFastSwimmer", "ZombieBeachSurfer"}:
                self.assertEqual(record["family"], "walk", name)

    def test_boss_mechs_are_gargantuars(self) -> None:
        for name in ("ZombieZombossMech_Egypt", "ZombieGeneralZmech"):
            self.assertEqual(self.records[name]["family"], "gargantuar", name)
        gargantuars = [name for name, record in self.records.items() if record["family"] == "gargantuar"]
        self.assertGreaterEqual(len(gargantuars), 20)

    def test_overrides_are_documented(self) -> None:
        for name in zclasses.OVERRIDES:
            record = self.records[name]
            self.assertTrue(record["note"].startswith("human override:"), name)
            self.assertGreater(len(record["note"]), len("human override:"), name)
            self.assertEqual(record["family"], zclasses.OVERRIDES[name][0], name)
        self.assertIn("13 classes carry a human override", "\n".join(self.payload["notes"]))

    def test_inc_table_matches_json(self) -> None:
        self.assertEqual(GENERATED_INC.read_text(encoding="utf-8").splitlines()[0], HEADER)
        entries = inc_entries()
        self.assertEqual(len(entries), 183)
        self.assertEqual([name for name, _ in entries], sorted(self.records))
        for name, family in entries:
            self.assertIn(family, zclasses.FAMILIES, name)
            self.assertEqual(family, self.records[name]["family"], name)

    def test_generation_is_byte_stable(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            first = Path(tmp) / "a"
            second = Path(tmp) / "b"
            for target in (first, second):
                target.mkdir()
                with contextlib.redirect_stdout(io.StringIO()):
                    code = zclasses.main(
                        [
                            "--obb",
                            str(OBB),
                            "--json",
                            str(target / "zombie_classes.json"),
                            "--inc",
                            str(target / "zombie_family_table.inc"),
                        ]
                    )
                self.assertEqual(code, 0)
            for name in ("zombie_classes.json", "zombie_family_table.inc"):
                self.assertEqual((first / name).read_bytes(), (second / name).read_bytes(), name)
                self.assertEqual((first / name).read_bytes(), (REPO / "native" / "generated" / name).read_bytes(), name)

    def test_check_mode_accepts_the_committed_artifacts(self) -> None:
        with contextlib.redirect_stdout(io.StringIO()):
            code = zclasses.main(["--obb", str(OBB), "--check"])
        self.assertEqual(code, 0)


if __name__ == "__main__":
    unittest.main(verbosity=2)

