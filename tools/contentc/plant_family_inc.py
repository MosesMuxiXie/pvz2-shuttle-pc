"""Emit the C++ plant-family lookup table from ``plant_families.json``.

``native/src/engine/plant_family.cpp`` includes ``plant_family_table.inc`` and
binary-searches it, exactly like the zombie class table.  Keeping the emitter
separate from ``pfamilies.py`` means the judgement rules (and their evidence)
stay in one place while the C++ table stays a mechanical projection.

Usage::

    python tools/contentc/plant_family_inc.py           # write the table
    python tools/contentc/plant_family_inc.py --check   # fail when it drifts
"""

from __future__ import annotations

import argparse
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
DEFAULT_JSON = REPO / "native" / "generated" / "plant_families.json"
DEFAULT_INC = REPO / "native" / "generated" / "plant_family_table.inc"

HEADER = "// generated by tools/contentc/plant_family_inc.py -- do not edit\n"


def load_rows(path: pathlib.Path) -> list[tuple[str, str]]:
    import json

    data = json.loads(path.read_text(encoding="utf-8"))
    rows = data["plants"] if isinstance(data, dict) else data
    out: list[tuple[str, str]] = []
    seen: set[str] = set()
    for row in rows:
        plant_id = row["id"]
        family = row["family"]
        if not plant_id or not family:
            raise SystemExit(f"empty id/family in {path}: {row!r}")
        if plant_id in seen:
            raise SystemExit(f"duplicate id in {path}: {plant_id}")
        seen.add(plant_id)
        out.append((plant_id, family))
    out.sort(key=lambda item: item[0])
    return out


def render(rows: list[tuple[str, str]]) -> str:
    body = "".join(f'{{"{plant_id}", "{family}"}},\n' for plant_id, family in rows)
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=pathlib.Path, default=DEFAULT_JSON)
    parser.add_argument("--inc", type=pathlib.Path, default=DEFAULT_INC)
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args(argv)

    rows = load_rows(args.json)
    text = render(rows)
    if args.check:
        if not args.inc.exists():
            print(f"[fail] missing {args.inc}", file=sys.stderr)
            return 1
        current = args.inc.read_text(encoding="utf-8")
        if current != text:
            print(f"[fail] {args.inc} is stale; run python tools/contentc/plant_family_inc.py", file=sys.stderr)
            return 1
        print(f"[ok] {args.inc.name}: {len(rows)} plant families")
        return 0

    args.inc.parent.mkdir(parents=True, exist_ok=True)
    args.inc.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.inc} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
